#!/usr/bin/env python3
"""Build Matriarch's per-tool files from the single sources in this repository.

Sources:   plugin.json, personas/*.md, skills/*/SKILL.md, core/, standards/
Generates: .claude-plugin/plugin.json, .claude-plugin/marketplace.json,
           .claude-plugin/agents/*.md (one read-only agent per persona),
           .codex-plugin/plugin.json, .agents/plugins/marketplace.json,
           dashboard/settings.html (the settings dashboard, from
           dashboard/template.html with the defaults, schema and comments inlined),
           dist/claude-ai/<skill>.zip (each skill bundled with core/, personas/,
           standards/ under matriarch/, for uploading to claude.ai).

Usage:
  python3 scripts/build.py          write everything
  python3 scripts/build.py --check  fail if any generated file is out of date
                                    (dist/ is not checked; it is not committed)
"""
from __future__ import annotations

import json
import re
import sys
import zipfile
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SHARED = ("core", "personas", "standards", "settings")
HEADER = "<!-- Generated by scripts/build.py from {src}. Do not edit by hand. -->\n"


def frontmatter(path: Path) -> tuple[dict, str]:
    """Parse the small YAML subset used here: key: value and key: [a, b]."""
    text = path.read_text(encoding="utf-8")
    m = re.match(r"^---\n(.*?)\n---\n(.*)$", text, re.S)
    if not m:
        raise SystemExit(f"{path}: missing frontmatter")
    meta: dict = {}
    for line in m.group(1).splitlines():
        if not line.strip():
            continue
        key, _, value = line.partition(":")
        value = value.strip()
        if value.startswith("[") and value.endswith("]"):
            meta[key.strip()] = [v.strip() for v in value[1:-1].split(",") if v.strip()]
        else:
            meta[key.strip()] = value
    return meta, m.group(2)


def personas() -> list[Path]:
    return sorted(p for p in (ROOT / "personas").glob("*.md") if not p.name.startswith("_"))


def skills() -> list[Path]:
    return sorted(p.parent for p in (ROOT / "skills").glob("*/SKILL.md"))


def claude_agent(persona: Path) -> str:
    meta, _ = frontmatter(persona)
    tools = meta.get("claude-tools", ["Read", "Grep", "Glob"])
    lines = [
        "---",
        f"name: {meta['name']}",
        f"description: {meta['description']}",
        "license: Apache-2.0",
        f"tools: [{', '.join(tools)}]",
        "model: inherit",
        f"color: {meta.get('claude-color', 'blue')}",
    ]
    is_reviewer = "Agent" not in tools
    if is_reviewer:
        lines.append("omitClaudeMd: true")
    lines.append("---")
    lines.append(HEADER.format(src=f"personas/{persona.name}").rstrip())
    lines.append("")
    if is_reviewer:
        lines.append(
            "Read `${CLAUDE_PLUGIN_ROOT}/personas/_mandates.md`, then "
            f"`${{CLAUDE_PLUGIN_ROOT}}/personas/{persona.name}`, and follow them. "
            "Standards are in `${CLAUDE_PLUGIN_ROOT}/standards/`. You have read-only "
            "tools and no project memory; review only what your prompt gives you."
        )
    else:
        lines.append(
            f"Read `${{CLAUDE_PLUGIN_ROOT}}/personas/{persona.name}` and follow it. "
            "Start each lens with the Agent tool as the plugin agent "
            "`matriarch:<lens>`, passing only the inputs the Elephant gave."
        )
    return "\n".join(lines) + "\n"


def manifests() -> dict[str, str]:
    base = json.loads((ROOT / "plugin.json").read_text(encoding="utf-8"))
    agents = [f"./.claude-plugin/agents/{p.name}" for p in personas()]
    claude = {**base, "agents": agents, "mcpServers": "./.mcp.json"}
    claude_market = {
        "name": base["name"],
        "owner": base["author"],
        "plugins": [{"name": base["name"], "source": "./", "description": base["description"],
                     "version": base["version"]}],
    }
    codex = {
        "name": base["name"],
        "version": base["version"],
        "description": base["description"],
        "author": base["author"],
        "repository": base["repository"],
        "license": base["license"],
        "skills": "./skills/",
        "requires_local_executor": True,
        "interface": {
            "displayName": base["displayName"],
            "shortDescription": "Elephant-Goldfish with Notion memory",
            "longDescription": (
                "Plan, build and review work with sessions that share one project memory in "
                "Notion. Fresh goldfish reviewers check specs, plans and pull requests without "
                "the earlier conversation. Needs the Notion connector."
            ),
            "developerName": base["author"]["name"],
            "category": "Productivity",
            "capabilities": ["Keep project memory", "Review designs and PRs", "Record decisions"],
            "defaultPrompt": [
                "matriarch:status",
                "matriarch:plan <task ID or idea>",
                "matriarch:discuss <topic>",
            ],
        },
    }
    codex_market = {
        "name": base["name"],
        "interface": {"displayName": base["displayName"]},
        "plugins": [
            {
                "name": base["name"],
                "source": "./",
                "policy": {"installation": "AVAILABLE", "authentication": "ON_INSTALL"},
                "category": "Productivity",
            }
        ],
    }
    dump = lambda d: json.dumps(d, indent=2, ensure_ascii=False) + "\n"  # noqa: E731
    return {
        ".claude-plugin/plugin.json": dump(claude),
        ".claude-plugin/marketplace.json": dump(claude_market),
        ".codex-plugin/plugin.json": dump(codex),
        ".agents/plugins/marketplace.json": dump(codex_market),
    }


def setting_docs(text: str) -> dict[str, str]:
    """Comments written above each key in defaults.yaml, by dotted path."""
    docs: dict[str, str] = {}
    stack: list[tuple[int, str]] = []
    pending: list[str] = []
    for line in text.splitlines():
        stripped = line.strip()
        if not stripped:
            pending = []
            continue
        if stripped.startswith("#"):
            # Keep indentation after "# " so YAML examples stay readable.
            pending.append(re.sub(r"^#+ ?", "", stripped).rstrip())
            continue
        m = re.match(r"^(\s*)([A-Za-z_][\w-]*):", line)
        if not m:
            pending = []
            continue
        indent = len(m.group(1))
        while stack and stack[-1][0] >= indent:
            stack.pop()
        stack.append((indent, m.group(2)))
        if pending:
            docs[".".join(k for _, k in stack)] = "\n".join(pending).strip()
        pending = []
    return docs


def dashboard() -> str:
    import yaml  # noqa: PLC0415  (PyYAML is a dependency, see pyproject.toml)

    text = (ROOT / "settings/defaults.yaml").read_text(encoding="utf-8")
    data = {
        "defaults": yaml.safe_load(text),
        "schema": json.loads((ROOT / "settings/schema.json").read_text(encoding="utf-8")),
        "docs": setting_docs(text),
    }
    blob = json.dumps(data, ensure_ascii=False).replace("</", "<\\/")
    template = (ROOT / "dashboard/template.html").read_text(encoding="utf-8")
    if "/*__DATA__*/null" not in template:
        raise SystemExit("dashboard/template.html: missing the /*__DATA__*/null placeholder")
    note = "<!DOCTYPE html>\n<!-- Generated by scripts/build.py from dashboard/template.html. Do not edit by hand. -->"
    return template.replace("/*__DATA__*/null", blob).replace("<!DOCTYPE html>", note, 1)


def generated() -> dict[str, str]:
    files = manifests()
    files["dashboard/settings.html"] = dashboard()
    for p in personas():
        files[f".claude-plugin/agents/{p.name}"] = claude_agent(p)
    return files


def _junk(path: Path) -> bool:
    """Caches and hidden files never go into a release zip."""
    return any(part == "__pycache__" or part.startswith(".") for part in path.parts[len(ROOT.parts):])


# Frontmatter keys claude.ai accepts in an uploaded skill; others are dropped
# from the zips (for example disable-model-invocation, a Claude Code key).
CLAUDE_AI_KEYS = {"name", "description", "license", "allowed-tools", "metadata", "compatibility"}


def claude_ai_frontmatter(text: str) -> str:
    m = re.match(r"^---\n(.*?)\n---\n", text, re.S)
    if not m:
        return text
    kept = [l for l in m.group(1).splitlines()
            if not re.match(r"^([A-Za-z][\w-]*):", l) or re.match(r"^([A-Za-z][\w-]*):", l).group(1) in CLAUDE_AI_KEYS]
    return "---\n" + "\n".join(kept) + "\n---\n" + text[m.end():]


def build_zips() -> list[Path]:
    out = ROOT / "dist" / "claude-ai"
    for old in out.glob("*.zip") if out.exists() else []:
        old.unlink()
    out.mkdir(parents=True, exist_ok=True)
    made = []
    for skill in skills():
        # claude.ai has no plugin namespace, so skills get a "matriarch-" prefix
        # there (matriarch-plan) to avoid clashing with other skills.
        name = f"matriarch-{skill.name}"
        target = out / f"{name}.zip"
        with zipfile.ZipFile(target, "w", zipfile.ZIP_DEFLATED) as z:
            for f in sorted(skill.rglob("*")):
                if not f.is_file() or _junk(f):
                    continue
                arc = f"{name}/{f.relative_to(skill)}"
                if f.name == "SKILL.md":
                    text = f.read_text(encoding="utf-8")
                    text = re.sub(r"^name: .*$", f"name: {name}", text, count=1, flags=re.M)
                    text = claude_ai_frontmatter(text)
                    z.writestr(arc, text)
                else:
                    z.write(f, arc)
            for shared in SHARED:
                for f in sorted((ROOT / shared).rglob("*")):
                    if f.is_file() and not _junk(f):
                        z.write(f, f"{name}/matriarch/{shared}/{f.relative_to(ROOT / shared)}")
        made.append(target)
    return made


def main() -> int:
    check = "--check" in sys.argv
    files = generated()
    stale = []
    agents_dir = ROOT / ".claude-plugin" / "agents"
    expected_agents = {k for k in files if k.startswith(".claude-plugin/agents/")}
    if agents_dir.exists():
        for f in agents_dir.glob("*.md"):
            rel = f".claude-plugin/agents/{f.name}"
            if rel not in expected_agents:
                stale.append(rel)
                if not check:
                    f.unlink()
    for rel, content in files.items():
        path = ROOT / rel
        current = path.read_text(encoding="utf-8") if path.exists() else None
        if current != content:
            stale.append(rel)
            if not check:
                path.parent.mkdir(parents=True, exist_ok=True)
                path.write_text(content, encoding="utf-8")
    if check:
        if stale:
            print("Out of date (run python3 scripts/build.py):\n  " + "\n  ".join(stale))
            return 1
        print("Generated files are current.")
        return 0
    for z in build_zips():
        print(f"built {z.relative_to(ROOT)}")
    print(f"updated {len(stale)} generated file(s)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
